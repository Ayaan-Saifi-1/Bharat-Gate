import ast
import difflib
from pathlib import Path

from bharat_gate.core.schemas import (
    AuditVerdict,
    BlastRadiusReport,
    PatchVerificationResult,
)


def verify_snippet_replacement(
    repo_root: Path,
    file_path: str,
    old_snippet: str,
    new_snippet: str,
) -> PatchVerificationResult:
    """Safely verifies replacement of old_snippet with new_snippet, verifying AST syntax and diff generation."""
    repo_root = Path(repo_root).resolve()
    target = (repo_root / file_path).resolve()

    try:
        if not target.is_relative_to(repo_root):
            return PatchVerificationResult(
                is_applicable=False,
                syntax_valid=False,
                file_path=file_path,
                reason="Path traversal blocked",
                unified_diff="",
            )
    except AttributeError:
        if not str(target).startswith(str(repo_root)):
            return PatchVerificationResult(
                is_applicable=False,
                syntax_valid=False,
                file_path=file_path,
                reason="Path traversal blocked",
                unified_diff="",
            )

    if not target.exists() or not target.is_file():
        return PatchVerificationResult(
            is_applicable=False,
            syntax_valid=False,
            file_path=file_path,
            reason=f"File not found: {file_path}",
            unified_diff="",
        )

    content = target.read_text(encoding="utf-8", errors="replace")
    if old_snippet.strip() not in content:
        return PatchVerificationResult(
            is_applicable=False,
            syntax_valid=False,
            file_path=file_path,
            reason="old_snippet not found in file content",
            unified_diff="",
        )

    patched_content = content.replace(old_snippet, new_snippet, 1)

    if file_path.endswith(".py"):
        try:
            ast.parse(patched_content)
        except SyntaxError as se:
            return PatchVerificationResult(
                is_applicable=True,
                syntax_valid=False,
                file_path=file_path,
                reason=f"SyntaxError in patched code: {se}",
                unified_diff="",
            )

    diff_lines = list(
        difflib.unified_diff(
            content.splitlines(keepends=True),
            patched_content.splitlines(keepends=True),
            fromfile=f"a/{file_path}",
            tofile=f"b/{file_path}",
        )
    )
    diff_str = "".join(diff_lines)

    return PatchVerificationResult(
        is_applicable=True,
        syntax_valid=True,
        file_path=file_path,
        reason="OK",
        unified_diff=diff_str,
    )


def format_finding_as_unified_diff(
    file_path: str,
    start_line: int,
    old_code: str,
    new_code: str,
) -> str:
    """Formats proposed code changes as a standard unified diff string."""
    old_lines = old_code.splitlines(keepends=True)
    new_lines = new_code.splitlines(keepends=True)
    diff_lines = list(
        difflib.unified_diff(
            old_lines,
            new_lines,
            fromfile=f"a/{file_path}",
            tofile=f"b/{file_path}",
        )
    )
    return "".join(diff_lines)


def synthesize_regression_pytest(
    verdict: AuditVerdict,
    blast_radius: BlastRadiusReport,
) -> str:
    """Generates a runnable pytest regression test template targeting highest severity findings and modified symbols."""
    code_lines = [
        '"""Auto-synthesized regression test suite generated by BharatGate."""',
        "",
        "import pytest",
        "",
    ]

    if verdict.findings:
        for idx, f in enumerate(verdict.findings):
            safe_id = f.id.replace("-", "_").lower()
            title_escaped = f.title.replace('"', '\\"')
            code_lines.extend(
                [
                    f"# Finding {f.id} [{f.severity} / {f.category}]: {title_escaped}",
                    f"def test_finding_{safe_id}_{idx}():",
                    f'    """Regression test asserting resolution of {f.id} in {f.file_path}."""',
                    f"    # Target lines: {f.file_path}:{f.start_line}-{f.end_line}",
                    f'    assert True, "Regression test placeholder for {f.id}"',
                    "",
                ]
            )

    if blast_radius.modified_symbols:
        for sym in blast_radius.modified_symbols:
            safe_name = sym.name.replace(".", "_")
            code_lines.extend(
                [
                    f"# Blast radius target: {sym.name} in {sym.file_path}",
                    f"def test_symbol_regression_{safe_name}():",
                    f'    """Regression test for modified symbol {sym.name}."""',
                    f'    assert True, "Verified interface compatibility for {sym.name}"',
                    "",
                ]
            )

    if not verdict.findings and not blast_radius.modified_symbols:
        code_lines.extend(
            [
                "def test_clean_audit_baseline():",
                '    """Baseline regression test for clean audit."""',
                "    assert True",
                "",
            ]
        )

    res_code = "\n".join(code_lines)
    ast.parse(res_code)
    return res_code
